import { z } from 'zod';

export const ParsedIntentEnum = z.enum([
  'sale',
  'credit',
  'payment',
  'expense',
  'proof',
  'stock',
  'recovery',
  'summary',
  'ordering',
  'confirm_yes',
  'confirm_no',
  'undo',
  'reminder_settings',
  'set_selling_price',
  'set_cost_price',
  'open_bill_scan',
  'open_stock',
  'open_ledger',
  'open_today',
  'show_low_stock',
  'order_item',
  'build_order_list',
  'send_order',
  'show_customer_ledger',
  'recent_transactions',
  'top_debtors',
  'monthly_credit_summary',
  'next',
  'previous',
  'repeat',
  'back',
  'close',
  'today',
  'yesterday',
  'this_week',
  'play_proof',
  'edit_entry',
  'change_amount',
  'change_item',
  'change_customer',
  'change_quantity',
  'change_date',
  'edit_note',
  'unknown',
]);

export type ParsedIntent = z.infer<typeof ParsedIntentEnum>;

export const ParseResultSchema = z.object({
  intent: ParsedIntentEnum,
  customer: z.string().nullable().optional(),
  amount: z.number().nullable().optional(),
  item: z.string().nullable().optional(),
  quantity: z.number().nullable().optional(),
  unit: z.string().nullable().optional(),
  oldPrice: z.number().nullable().optional(),
  count: z.number().nullable().optional(),
  timeframe: z.enum(['today', 'yesterday', 'this_week', 'month']).nullable().optional(),
  targetTab: z.enum(['home', 'ledger', 'stock', 'today', 'bill_scan', 'supplier_orders', 'recovery']).nullable().optional(),
  language: z.enum(['hi', 'en', 'pa', 'gu', 'mr', 'bn', 'ta', 'te', 'kn', 'ml']),
  confidence: z.number().min(0).max(1),
  rawText: z.string().default(''),
  spokenReply: z.string().optional(),
  questionToAsk: z.string().nullable().optional(),
});

export type ValidatedParseResult = z.infer<typeof ParseResultSchema>;
